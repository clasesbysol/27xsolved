create or replace function public.jwt_email()
returns text language sql stable
as $$ select lower(coalesce(auth.jwt()->>'email','')) $$;

-- ---------- Perfil del alumno (año, aviso de actividad, temas vistos) ----------
create table if not exists public.student_profiles (
  email text primary key,
  full_name text,
  year integer check (year between 1 and 7),
  year_set_by text check (year_set_by in ('student','admin')),
  year_updated_at timestamptz,
  activity_notice_at timestamptz,
  seen jsonb not null default '{}'::jsonb,
  continue_item jsonb,
  last_seen_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
alter table public.student_profiles enable row level security;
drop policy if exists "student profile read" on public.student_profiles;
drop policy if exists "student profile insert" on public.student_profiles;
drop policy if exists "student profile update" on public.student_profiles;
create policy "student profile read" on public.student_profiles for select to authenticated
  using (lower(email)=public.jwt_email() or public.is_cbc_admin());
create policy "student profile insert" on public.student_profiles for insert to authenticated
  with check (lower(email)=public.jwt_email() or public.is_cbc_admin());
create policy "student profile update" on public.student_profiles for update to authenticated
  using (lower(email)=public.jwt_email() or public.is_cbc_admin())
  with check (lower(email)=public.jwt_email() or public.is_cbc_admin());

-- ---------- Historial de cambios de año ----------
create table if not exists public.student_year_changes (
  id bigint generated by default as identity primary key,
  email text not null,
  from_year integer,
  to_year integer not null,
  changed_by text not null check (changed_by in ('student','admin')),
  changed_at timestamptz not null default now()
);
alter table public.student_year_changes enable row level security;
drop policy if exists "year change insert" on public.student_year_changes;
drop policy if exists "year change read" on public.student_year_changes;
create policy "year change insert" on public.student_year_changes for insert to authenticated
  with check (lower(email)=public.jwt_email() or public.is_cbc_admin());
create policy "year change read" on public.student_year_changes for select to authenticated
  using (lower(email)=public.jwt_email() or public.is_cbc_admin());

-- ---------- Horario semanal y tareas (privados de cada alumno) ----------
create table if not exists public.student_planner (
  email text primary key,
  schedule jsonb not null default '[]'::jsonb,
  checklist jsonb not null default '[]'::jsonb,
  updated_at timestamptz not null default now()
);
alter table public.student_planner enable row level security;
drop policy if exists "planner own" on public.student_planner;
create policy "planner own" on public.student_planner for all to authenticated
  using (lower(email)=public.jwt_email())
  with check (lower(email)=public.jwt_email());

-- ---------- Actividad (ingresos y temas abiertos) ----------
create table if not exists public.activity_events (
  id bigint generated by default as identity primary key,
  email text not null default public.jwt_email(),
  kind text not null check (kind in ('app_open','topic_open')),
  subject text,
  topic text,
  label text,
  created_at timestamptz not null default now()
);
alter table public.activity_events enable row level security;
drop policy if exists "activity insert own" on public.activity_events;
drop policy if exists "activity admin read" on public.activity_events;
create policy "activity insert own" on public.activity_events for insert to authenticated
  with check (lower(email)=public.jwt_email());
create policy "activity admin read" on public.activity_events for select to authenticated
  using (public.is_cbc_admin());
create index if not exists activity_events_created_idx on public.activity_events(created_at desc);
create index if not exists activity_events_email_idx on public.activity_events(lower(email),created_at desc);
create index if not exists activity_events_subject_idx on public.activity_events(subject,topic);
